
package com.charron.api.loading.application;

import com.charron.api.loading.domain.LoadingPlan;
import com.charron.api.loading.domain.LoadingPlanArrangement;
import com.charron.api.loading.domain.LoadingPlanCargo;
import tools.jackson.databind.json.JsonMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class LoadingPlanArrangementServiceTest {

    private LoadingPlanArrangementRepository repository;
    private LoadingPlanService loadingPlanService;
    private LoadingPlanCargoRepository cargoRepository;
    private LoadingPlanArrangementService service;

    private UUID planId;
    private UUID cargoSpaceId;
    private UUID cargoId;

    @BeforeEach
    void setUp() {
        repository = mock(LoadingPlanArrangementRepository.class);
        loadingPlanService = mock(LoadingPlanService.class);
        cargoRepository = mock(LoadingPlanCargoRepository.class);

        service = new LoadingPlanArrangementService(
                repository,
                loadingPlanService,
                cargoRepository,
                JsonMapper.builder().build()
        );

        planId = UUID.randomUUID();
        cargoSpaceId = UUID.randomUUID();
        cargoId = UUID.randomUUID();

        LoadingPlan plan = LoadingPlan.create(
                UUID.randomUUID(),
                UUID.randomUUID(),
                cargoSpaceId
        );

        when(loadingPlanService.getById(planId))
                .thenReturn(plan);

        when(cargoRepository.findByLoadingPlanId(planId))
                .thenReturn(List.of(
                        LoadingPlanCargo.create(planId, cargoId, 3)
                ));
    }

    private String request(int quantity) {
        return """
                {
                  "cargoSpaceId": "%s",
                  "cargo": [
                    {
                      "cargoId": "%s",
                      "name": "Test Pallet",
                      "quantity": %d,
                      "lengthMm": 1200,
                      "widthMm": 1000,
                      "heightMm": 1500,
                      "weightGrams": 500000
                    }
                  ]
                }
                """.formatted(cargoSpaceId, cargoId, quantity);
    }

    private String preview(String status) {
        return """
                {
                  "cargoSpaceId": "%s",
                  "status": "%s",
                  "reason": "Generated by loading engine",
                  "placements": []
                }
                """.formatted(cargoSpaceId, status);
    }

    @Test
    void savesMatchingArrangement() {
        LoadingPlanArrangement result = service.save(
                planId,
                request(3),
                preview("VALID")
        );

        assertEquals(planId, result.loadingPlanId());
        assertEquals("VALID", result.status());
        assertEquals(1, result.formatVersion());

        verify(repository).save(result);
    }

    @Test
    void rejectsMismatchedQuantity() {
        assertThrows(
                LoadingPlanConflictException.class,
                () -> service.save(
                        planId,
                        request(2),
                        preview("VALID")
                )
        );

        verify(repository, never()).save(any());
    }

    @Test
    void rejectsWrongRequestCargoSpace() {
        String invalidRequest = request(3).replace(
                cargoSpaceId.toString(),
                UUID.randomUUID().toString()
        );

        assertThrows(
                InvalidLoadingPlanException.class,
                () -> service.save(
                        planId,
                        invalidRequest,
                        preview("VALID")
                )
        );

        verify(repository, never()).save(any());
    }

    @Test
    void rejectsWrongPreviewCargoSpace() {
        String invalidPreview = preview("VALID").replace(
                cargoSpaceId.toString(),
                UUID.randomUUID().toString()
        );

        assertThrows(
                InvalidLoadingPlanException.class,
                () -> service.save(
                        planId,
                        request(3),
                        invalidPreview
                )
        );

        verify(repository, never()).save(any());
    }

    @Test
    void rejectsUnknownCargo() {
        String invalidRequest = request(3).replace(
                cargoId.toString(),
                UUID.randomUUID().toString()
        );

        assertThrows(
                LoadingPlanConflictException.class,
                () -> service.save(
                        planId,
                        invalidRequest,
                        preview("VALID")
                )
        );
    }

    @Test
    void rejectsUnsupportedStatus() {
        assertThrows(
                InvalidLoadingPlanException.class,
                () -> service.save(
                        planId,
                        request(3),
                        preview("UNKNOWN")
                )
        );
    }

    @Test
    void rejectsMalformedJson() {
        assertThrows(
                InvalidLoadingPlanException.class,
                () -> service.save(
                        planId,
                        "{ invalid json }",
                        preview("VALID")
                )
        );
    }

    @Test
    void rejectsMissingPlacementsArray() {
        String invalidPreview = """
                {
                  "cargoSpaceId": "%s",
                  "status": "VALID",
                  "reason": "Missing placements"
                }
                """.formatted(cargoSpaceId);

        assertThrows(
                InvalidLoadingPlanException.class,
                () -> service.save(
                        planId,
                        request(3),
                        invalidPreview
                )
        );
    }

    @Test
    void retrievesExistingArrangement() {
        LoadingPlanArrangement arrangement =
                LoadingPlanArrangement.create(
                        planId,
                        request(3),
                        preview("VALID"),
                        "VALID"
                );

        when(repository.findByLoadingPlanId(planId))
                .thenReturn(Optional.of(arrangement));

        assertEquals(
                Optional.of(arrangement),
                service.findByLoadingPlanId(planId)
        );
    }

    @Test
    void returnsEmptyWhenNoArrangementExists() {
        assertTrue(
                service.findByLoadingPlanId(planId).isEmpty()
        );
    }

    @Test
    void rejectsUnknownLoadingPlan() {
        when(loadingPlanService.getById(planId))
                .thenThrow(new LoadingPlanNotFoundException(
                        "Loading plan does not exist"
                ));

        assertThrows(
                LoadingPlanNotFoundException.class,
                () -> service.save(
                        planId,
                        request(3),
                        preview("VALID")
                )
        );

        verify(repository, never()).save(any());
    }

    @Test
    void preservesOriginalSavedTimestamp() {
        LoadingPlanArrangement original =
                LoadingPlanArrangement.create(
                        planId,
                        request(3),
                        preview("VALID"),
                        "VALID"
                );

        when(repository.findByLoadingPlanId(planId))
                .thenReturn(Optional.of(original));

        LoadingPlanArrangement updated = service.save(
                planId,
                request(3),
                preview("INVALID")
        );

        assertEquals(original.savedAt(), updated.savedAt());
        assertEquals("INVALID", updated.status());

        verify(repository).save(updated);
    }
}
